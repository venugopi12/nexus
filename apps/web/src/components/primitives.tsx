export function ErrorState({ error, onRetry, compact }: { error: unknown; onRetry?: () => void; compact?: boolean }) {
  const msg = error instanceof Error ? error.message : 'Something went wrong';
  return (
    <div role="alert" className={cn('flex flex-col items-center justify-center gap-2 text-center', compact ? 'py-6' : 'py-10')}>
      <div className="grid size-9 place-items-center rounded-full bg-crit-soft text-crit"><AlertTriangle className="size-4" /></div>
      <p className="text-sm font-medium">Couldn’t load this</p>
      <p className="max-w-xs text-xs text-muted-foreground">{msg}</p>
      {onRetry && <Button size="sm" variant="outline" onClick={onRetry}><RefreshCw /> Retry</Button>}
    </div>
  );
}

