/* ----------------------------------------------------------------- animated number */
export function AnimatedNumber({ value, format, className }: { value: number; format: (n: number) => string; className?: string }) {
  const reduce = useReducedMotion();
  const mv = useMotionValue(value);
  const text = useTransform(mv, (v) => format(v));
  const first = useRef(true);
  useEffect(() => {
    if (first.current || reduce) {
      mv.set(value);
      first.current = false;
      return;
    }
    const controls = animate(mv, value, { duration: 0.6, ease: [0.16, 1, 0.3, 1] });
    return () => controls.stop();
  }, [value, mv, reduce]);
  return <motion.span className={cn('tabular', className)}>{text}</motion.span>;
}

export function Sparkline({ points, color = 'var(--primary)', className }: { points: (number | null)[]; color?: string; className?: string }) {
  const vals = points.filter((p): p is number => p !== null);
  if (vals.length < 2) return <div className={cn('h-8', className)} />;
  const min = Math.min(...vals);
  const max = Math.max(...vals);
  const span = max - min || 1;
  const w = 100;
  const h = 28;
  const step = w / (points.length - 1);
  let d = '';
  points.forEach((p, i) => {
    if (p === null) return;
    d += `${d ? 'L' : 'M'}${(i * step).toFixed(1)},${(h - 2 - ((p - min) / span) * (h - 4)).toFixed(1)}`;
  });
  return (
    <svg viewBox={`0 0 ${w} ${h}`} preserveAspectRatio="none" className={cn('h-8 w-full overflow-visible', className)} aria-hidden>
      <path d={d} fill="none" stroke={color} strokeWidth="1.5" strokeLinejoin="round" strokeLinecap="round" vectorEffect="non-scaling-stroke" />
    </svg>
  );
}
