/* ----------------------------------------------------------------- status */
const STATUS_STYLE: Record<HealthStatus, { dot: string; text: string; bg: string; label: string }> = {
  healthy: { dot: 'bg-ok', text: 'text-ok', bg: 'bg-ok-soft', label: 'Healthy' },
  degraded: { dot: 'bg-warn', text: 'text-warn', bg: 'bg-warn-soft', label: 'Degraded' },
  unavailable: { dot: 'bg-crit', text: 'text-crit', bg: 'bg-crit-soft', label: 'Unavailable' },
};
export const statusLabel = (s: HealthStatus) => STATUS_STYLE[s].label;

export function StatusBadge({ status, className, compact, atRisk }: { status: HealthStatus; className?: string; compact?: boolean; atRisk?: boolean }) {
  const st = atRisk ? { dot: 'bg-warn/60', text: 'text-warn', bg: 'bg-warn-soft', label: 'At risk (inferred)' } : STATUS_STYLE[status];
  return (
    <motion.span layout="position" transition={spring.snappy} className={cn('inline-flex items-center gap-1.5 rounded-full px-2 py-0.5 text-xs font-medium', st.bg, st.text, className)}>
      <span className={cn('size-1.5 rounded-full', st.dot, status !== 'healthy' && !atRisk && 'animate-pulse-dot')} />
      {!compact && st.label}
    </motion.span>
  );
}

export function StatusDot({ status, className }: { status: HealthStatus; className?: string }) {
  return <span role="img" aria-label={STATUS_STYLE[status].label} className={cn('inline-block size-2 rounded-full', STATUS_STYLE[status].dot, className)} />;
}

